-- Shared subject catalogue; preserve historic test subjects as initial class assignments.
-- The original tests.subject column is a subject_name enum on existing installations.
-- A catalogue supports arbitrary new subjects, so retain its values as text.
alter table public.tests alter column subject type text using subject::text;
create table public.subjects (id bigint generated by default as identity primary key, name text not null unique check (length(trim(name)) > 0));
create table public.class_subjects (
  class_id bigint not null references public.classes(id) on delete cascade,
  subject_id bigint not null references public.subjects(id) on delete cascade,
  primary key (class_id, subject_id)
);
insert into public.subjects(name) select distinct trim(subject) from public.tests where nullif(trim(subject),'') is not null on conflict do nothing;
insert into public.class_subjects(class_id,subject_id)
select distinct t.class_id,s.id from public.tests t join public.subjects s on s.name=trim(t.subject) join public.classes c on c.id=t.class_id on conflict do nothing;

create table public.school_timetable (
  id integer primary key check(id=1), draft jsonb not null default '{"title":"Weekly timetable","days":{},"colors":{"classes":{},"teachers":{}}}',
  published jsonb, revision integer not null default 0, published_at timestamptz, updated_at timestamptz not null default now()
);
insert into public.school_timetable(id) values(1);

-- One normalized row per staff lesson, used for access and change detection.
create function public.timetable_lessons(plan jsonb)
returns table(teacher_id text, class_id text, detail jsonb)
language sql immutable as $$
  select teacher.value #>> '{}', lesson.key,
    jsonb_build_object('day',d.key,'start',slot->>'start','end',slot->>'end','label',slot->>'label','class',lesson.key,'subject',lesson.value->>'subjectId','teachers',lesson.value->'teacherIds')
  from jsonb_each(coalesce(plan->'days','{}')) d
  cross join lateral jsonb_array_elements(d.value) slot
  cross join lateral jsonb_each(coalesce(slot->'lessons','{}')) lesson
  cross join lateral jsonb_array_elements(coalesce(lesson.value->'teacherIds','[]')) teacher;
$$;

create view public.teacher_class_access as
select teacher_profile, class from public.teacher_class
union
select p.id, c.id from public.school_timetable t
cross join lateral public.timetable_lessons(t.published) l
join public.profiles p on p.id::text=l.teacher_id
join public.classes c on c.id::text=l.class_id;

-- Publishing and queue insertion are a single transaction. Revision checks prevent stale edits.
create function public.save_school_timetable(p_plan jsonb, p_revision integer, p_publish boolean default false)
returns jsonb language plpgsql security definer set search_path=public as $$
declare current_row school_timetable; actor text; queued integer := 0; affected integer := 0;
begin
  select lower(role) into actor from profiles where id=auth.uid() and is_active is not false;
  if actor is null or actor not in ('admin','superadmin') then raise exception 'Administrator access required'; end if;
  select * into current_row from school_timetable where id=1 for update;
  if current_row.revision<>p_revision then raise exception 'Another editor saved changes. Reload before saving.'; end if;
  if jsonb_typeof(p_plan->'days') is distinct from 'object' then raise exception 'Invalid timetable'; end if;
  if exists (
    select 1 from jsonb_each(p_plan->'days') d cross join lateral jsonb_array_elements(d.value) s
    where coalesce(s->>'start','') !~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'
       or coalesce(s->>'end','') !~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'
       or s->>'start'>=s->>'end'
       or (s->>'kind'='break' and coalesce(s->'lessons','{}')<>'{}'::jsonb)
  ) then raise exception 'Invalid slot times or break assignments'; end if;
  if exists (
    select 1 from jsonb_each(p_plan->'days') d cross join lateral jsonb_array_elements(d.value) s
    cross join lateral jsonb_each(coalesce(s->'lessons','{}')) l
    where not exists(select 1 from class_subjects cs where cs.class_id::text=l.key and cs.subject_id::text=l.value->>'subjectId')
      or jsonb_array_length(coalesce(l.value->'teacherIds','[]'))=0
      or exists(select 1 from jsonb_array_elements_text(l.value->'teacherIds') staff where not exists (
        select 1 from profiles p where p.id::text=staff and lower(p.role) in ('teacher','admin','superadmin') and p.is_active is not false
      ))
  ) then raise exception 'Each lecture must have a class subject and active staff'; end if;
  if actor='admin' and (
    (select coalesce(jsonb_object_agg(d.key, (select coalesce(jsonb_agg(s - 'lessons' order by ord),'[]') from jsonb_array_elements(d.value) with ordinality a(s,ord))),'{}') from jsonb_each(p_plan->'days') d)
    is distinct from
    (select coalesce(jsonb_object_agg(d.key, (select coalesce(jsonb_agg(s - 'lessons' order by ord),'[]') from jsonb_array_elements(d.value) with ordinality a(s,ord))),'{}') from jsonb_each(current_row.draft->'days') d)
  ) then raise exception 'Only superadmins may change day slots or timings'; end if;
  if p_publish then
    with old_schedule as (
      select teacher_id,jsonb_agg(detail order by detail::text) details from timetable_lessons(current_row.published) group by teacher_id
    ), new_schedule as (
      select teacher_id,jsonb_agg(detail order by detail::text) details from timetable_lessons(p_plan) group by teacher_id
    ), changed as (
      select coalesce(o.teacher_id,n.teacher_id) id from old_schedule o full join new_schedule n using(teacher_id) where o.details is distinct from n.details
    ), recipients as (
      select p.* from profiles p join changed c on c.id=p.id::text where p.is_active is not false
    ), inserted as (
      insert into messages(number,sent,text)
      select mobilenumber,false,'Dear ' || coalesce(name,'Teacher') || ', your teaching timetable has changed. Please review the published weekly timetable at /timetable and download your updated teacher timetable. DAR-E-ARQAM School.'
      from recipients where nullif(trim(mobilenumber),'') is not null returning 1
    ) select (select count(*) from inserted),(select count(*) from recipients) into queued,affected;
  end if;
  update school_timetable set draft=p_plan, published=case when p_publish then p_plan else published end,
    published_at=case when p_publish then now() else published_at end,revision=revision+1,updated_at=now() where id=1;
  return jsonb_build_object('revision',p_revision+1,'queued',queued,'affected',affected);
end $$;
grant select,insert,update,delete on public.subjects,public.class_subjects to authenticated;
grant usage,select on sequence public.subjects_id_seq to authenticated;
grant select on public.school_timetable,public.teacher_class_access to authenticated;
revoke execute on function public.save_school_timetable(jsonb,integer,boolean) from public,anon;
grant execute on function public.save_school_timetable(jsonb,integer,boolean) to authenticated;

-- Keep historic test text intact, while validating all new/changed subject relationships.
create function public.check_test_class_subject() returns trigger language plpgsql set search_path=public as $$
begin
  if TG_OP='UPDATE' then
    if new.subject is not distinct from old.subject and new.class_id is not distinct from old.class_id then return new; end if;
  end if;
  if not exists(select 1 from class_subjects cs join subjects s on s.id=cs.subject_id where cs.class_id=new.class_id and s.name=new.subject) then
    raise exception 'Choose a subject assigned to this class';
  end if;
  return new;
end $$;
create trigger tests_class_subject before insert or update of subject,class_id on public.tests for each row execute function public.check_test_class_subject();

-- Existing queue actions must recognize timetable-derived access as well.
create or replace function public.manage_message_rows(p_ids bigint[], p_action text)
returns integer language plpgsql set search_path=public as $$
declare actor_role text; affected integer;
begin
  select lower(role) into actor_role from profiles where id=auth.uid();
  if actor_role is null or actor_role not in ('admin','superadmin','teacher') then raise exception 'Staff access is required'; end if;
  if coalesce(cardinality(p_ids),0)=0 or p_action is null or p_action not in ('mark_sent','cancel','delete_sent') then raise exception 'Select messages and a valid action'; end if;
  if p_action='mark_sent' then
    update messages m set sent=true where m.id=any(p_ids) and m.sent is not true and (m.created_at is null or m.created_at<=now())
      and (actor_role<>'teacher' or exists(select 1 from teacher_class_access tc where tc.teacher_profile=auth.uid() and tc.class=m.class_id));
  else
    delete from messages m where m.id=any(p_ids) and ((p_action='cancel' and m.sent is not true) or (p_action='delete_sent' and m.sent is true))
      and (actor_role<>'teacher' or exists(select 1 from teacher_class_access tc where tc.teacher_profile=auth.uid() and tc.class=m.class_id));
  end if;
  get diagnostics affected=row_count;
  if affected<>cardinality(p_ids) then raise exception 'Some messages changed or are outside your classes. Refresh the queue and try again.'; end if;
  return affected;
end $$;
