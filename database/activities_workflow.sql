-- Activity and event-management workflow
-- Run this in the Supabase SQL editor before using the new Activities page.
-- This deliberately does not modify the existing `activities` table, which is
-- used by the earlier daily subject-coverage tracker.

create table if not exists public.activity_committee_members (
  profile_id uuid primary key references public.profiles(id) on delete cascade,
  added_at timestamptz not null default now()
);

create table if not exists public.school_activities (
  id bigint generated by default as identity primary key,
  title text not null,
  status text not null default 'planned' check (status in ('planned', 'confirmed', 'in_progress', 'completed', 'cancelled')),
  description text,
  start_date date not null,
  end_date date,
  venue text,
  responsible_name text,
  responsible_profile uuid references public.profiles(id) on delete set null,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint school_activities_date_order check (end_date is null or end_date >= start_date)
);

create table if not exists public.school_activity_classes (
  activity_id bigint not null references public.school_activities(id) on delete cascade,
  class_id bigint not null references public.classes(id) on delete cascade,
  primary key (activity_id, class_id)
);

create index if not exists school_activities_start_date_idx on public.school_activities (start_date);
create index if not exists school_activity_classes_class_id_idx on public.school_activity_classes (class_id);

-- Optional convenience trigger for edits made outside the application.
create or replace function public.set_school_activity_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists school_activities_updated_at on public.school_activities;
create trigger school_activities_updated_at
before update on public.school_activities
for each row execute function public.set_school_activity_updated_at();
